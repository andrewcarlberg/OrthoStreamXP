using OrthoStreamXP.Setup;

namespace OrthoStreamXP.Tests;

public sealed class AirportFlatteningTests : IDisposable
{
    private const string Ebbr = """
        1    145 0 0 EBBR Brussels National
        1302 city Brussels
        1302 country BEL
        100 45.00 35 727 0.00 1 3 0 07R 50.8890356 4.4803936 126 0 6 0 0 2 25L 50.8989489 4.5233233 0 0 6 2 1 2
        """;

    private const string Lfmn = """
        1     12 0 0 LFMN Nice Cote d Azur
        1302 flatten 0
        100 45.00 1 0 0.00 1 3 0 04L 43.6513 7.2012 0 0 3 0 0 0 22R 43.6667 7.2205 0 0 3 0 0 0
        """;

    private const string Lsez = """
        17   5269 0 0 LSEZ Zermatt Heliport
        1302 flatten 1
        """;

    private readonly TempTree _tree = new();

    public void Dispose() => _tree.Dispose();

    private string XPlane => _tree.PathOf("X-Plane 12");
    private string ScenerypacksText => File.ReadAllText(_tree.PathOf("X-Plane 12/Custom Scenery/scenery_packs.ini"));
    private string PackageAptDat => _tree.PathOf($"X-Plane 12/Custom Scenery/{FlattenedAirports.PackageName}/Earth nav data/apt.dat");

    private static string AptDat(params string[] airports) =>
        "I\n1200 Generated by WorldEditor\n\n" + string.Join("\n\n", airports) + "\n\n99\n";

    private void WriteGlobalAirports(params string[] airports) =>
        _tree.WriteText("X-Plane 12/Global Scenery/Global Airports/Earth nav data/apt.dat", AptDat(airports));

    private void WriteSceneryPacks(params string[] entries) =>
        _tree.WriteText("X-Plane 12/Custom Scenery/scenery_packs.ini", "I\r\n1000 Version\r\nSCENERY\r\n\r\n" + string.Concat(entries.Select(e => e + "\r\n")));

    private AirportFlattening Flattening() => new(XPlane, new AirportCatalog());

    private static FlattenableAirport Find(IReadOnlyList<FlattenableAirport> airports, string ident) => airports.Single(a => a.Ident == ident);

    [Fact]
    public void An_apt_dat_lists_its_airports_with_their_place_and_flatten_flag()
    {
        string file = _tree.WriteText("apt.dat", AptDat(Ebbr, Lfmn, Lsez).ReplaceLineEndings("\r\n"));

        IReadOnlyList<AirportRecord> airports = AptDatReader.Read(file, CancellationToken.None);

        Assert.Equal(["EBBR", "LFMN", "LSEZ"], airports.Select(a => a.Ident));
        Assert.Equal("Brussels National", airports[0].Name);
        Assert.Equal("Brussels, BEL", airports[0].Place);
        Assert.Equal([false, false, true], airports.Select(a => a.Flattened));
        Assert.Equal("Zermatt Heliport", airports[2].Name);
        Assert.Null(airports[2].Place);
        // Each airport's lines are read back from where they were found.
        Assert.Equal("LFMN", AptDatReader.ReadBlock(file, airports[1]).Ident);
        Assert.True(AptDatReader.ReadBlock(file, airports[2]).IsFlattened);
    }

    [Fact]
    public void Lines_longer_than_the_read_buffer_and_a_file_without_an_end_line_are_read()
    {
        string longLine = "1302 gw_credits " + new string('x', 3 << 20);
        string file = _tree.WriteText("apt.dat", "I\n1200 Version\n\n" + Ebbr.Replace("1302 city", longLine + "\n1302 city") + "\n\n" + Lsez);

        IReadOnlyList<AirportRecord> airports = AptDatReader.Read(file, CancellationToken.None);

        Assert.Equal(["EBBR", "LSEZ"], airports.Select(a => a.Ident));
        Assert.Equal("Brussels", airports[0].City);
        Assert.True(airports[1].Flattened);
    }

    [Fact]
    public void Flattening_adds_the_flag_after_the_metadata_or_sets_the_one_there()
    {
        AirportBlock ebbr = new AirportBlock(Ebbr).Flattened();
        Assert.Equal(
            "1    145 0 0 EBBR Brussels National\r\n1302 city Brussels\r\n1302 country BEL\r\n1302 flatten 1\r\n100 45.00 35 727 0.00 1 3 0 07R 50.8890356 4.4803936 126 0 6 0 0 2 25L 50.8989489 4.5233233 0 0 6 2 1 2\r\n",
            ebbr.Text);
        Assert.True(ebbr.IsFlattened);

        AirportBlock lfmn = new AirportBlock(Lfmn).Flattened();
        Assert.Contains("1302 flatten 1", lfmn.Text, StringComparison.Ordinal);
        Assert.DoesNotContain("1302 flatten 0", lfmn.Text, StringComparison.Ordinal);
    }

    [Fact]
    public void The_highest_package_in_the_scenery_list_gives_an_airport_and_its_state()
    {
        WriteGlobalAirports(Ebbr, Lfmn, Lsez);
        _tree.WriteText("X-Plane 12/Custom Scenery/Aerosoft LFMN/Earth nav data/apt.dat", AptDat(Lfmn.Replace("Nice Cote d Azur", "Nice Aerosoft", StringComparison.Ordinal)));
        _tree.WriteText("X-Plane 12/Custom Scenery/Off EBBR/Earth nav data/apt.dat", AptDat(Ebbr.Replace("Brussels National", "Switched off", StringComparison.Ordinal)));
        WriteSceneryPacks("SCENERY_PACK Custom Scenery/Aerosoft LFMN/", "SCENERY_PACK_DISABLED Custom Scenery/Off EBBR/", "SCENERY_PACK *GLOBAL_AIRPORTS*");

        IReadOnlyList<FlattenableAirport> airports = Flattening().Load(CancellationToken.None);

        Assert.Equal("Nice Aerosoft", Find(airports, "LFMN").Name);
        Assert.Equal("Aerosoft LFMN", Find(airports, "LFMN").Source!.Source.Name);
        Assert.Equal("Brussels National", Find(airports, "EBBR").Name);
        Assert.Equal("Global Airports", Find(airports, "EBBR").Source!.Source.Name);
        Assert.Equal(FlattenState.NotFlattened, Find(airports, "EBBR").State);
        Assert.Equal(FlattenState.FlattenedByScenery, Find(airports, "LSEZ").State);
    }

    [Fact]
    public void Flattening_puts_a_flagged_copy_in_its_own_package_above_the_airports_scenery_and_undo_takes_it_out()
    {
        WriteGlobalAirports(Ebbr, Lsez);
        string sourceText = File.ReadAllText(_tree.PathOf("X-Plane 12/Global Scenery/Global Airports/Earth nav data/apt.dat"));
        WriteSceneryPacks("SCENERY_PACK Custom Scenery/KSEA Demo/", "SCENERY_PACK *GLOBAL_AIRPORTS*", "SCENERY_PACK Custom Scenery/OrthoStream_Eur/");
        AirportFlattening flattening = Flattening();

        FlattenableAirport flattened = flattening.Flatten(Find(flattening.Load(CancellationToken.None), "EBBR"));

        Assert.Equal(FlattenState.Flattened, flattened.State);
        Assert.True(flattened.InEffect);
        IReadOnlyList<AirportBlock> copies = AirportBlock.Split(File.ReadAllText(PackageAptDat));
        Assert.True(Assert.Single(copies).IsFlattened);
        Assert.StartsWith("I\r\n1200 Version", File.ReadAllText(PackageAptDat), StringComparison.Ordinal);
        Assert.EndsWith("99\r\n", File.ReadAllText(PackageAptDat), StringComparison.Ordinal);
        Assert.Equal(
            $"I\r\n1000 Version\r\nSCENERY\r\n\r\nSCENERY_PACK Custom Scenery/KSEA Demo/\r\nSCENERY_PACK {FlattenedAirports.EntryPath}\r\nSCENERY_PACK *GLOBAL_AIRPORTS*\r\nSCENERY_PACK Custom Scenery/OrthoStream_Eur/\r\n",
            ScenerypacksText);
        Assert.Equal(sourceText, File.ReadAllText(_tree.PathOf("X-Plane 12/Global Scenery/Global Airports/Earth nav data/apt.dat")));
        Assert.Equal(FlattenState.Flattened, Find(Flattening().Load(CancellationToken.None), "EBBR").State);

        FlattenableAirport undone = flattening.Undo(flattened);

        Assert.Equal(FlattenState.NotFlattened, undone.State);
        Assert.False(Directory.Exists(_tree.PathOf($"X-Plane 12/Custom Scenery/{FlattenedAirports.PackageName}")));
        Assert.DoesNotContain(FlattenedAirports.PackageName, ScenerypacksText, StringComparison.Ordinal);
        Assert.Equal(FlattenState.NotFlattened, Find(Flattening().Load(CancellationToken.None), "EBBR").State);
    }

    [Fact]
    public void Undoing_one_of_two_airports_keeps_the_other()
    {
        WriteGlobalAirports(Ebbr, Lfmn);
        WriteSceneryPacks("SCENERY_PACK *GLOBAL_AIRPORTS*");
        AirportFlattening flattening = Flattening();
        IReadOnlyList<FlattenableAirport> airports = flattening.Load(CancellationToken.None);
        flattening.Flatten(Find(airports, "LFMN"));
        FlattenableAirport ebbr = flattening.Flatten(Find(airports, "EBBR"));

        flattening.Undo(ebbr);

        Assert.Equal("LFMN", Assert.Single(AirportBlock.Split(File.ReadAllText(PackageAptDat))).Ident);
        Assert.Single(new OrthoStreamXP.Scenery.SceneryPackList(_tree.PathOf("X-Plane 12/Custom Scenery")).Read(), e => e.IsAt(FlattenedAirports.EntryPath));
    }

    [Fact]
    public void A_package_moved_below_the_airports_scenery_is_not_in_effect_until_flattened_again()
    {
        _tree.WriteText("X-Plane 12/Custom Scenery/Brussels HD/Earth nav data/apt.dat", AptDat(Ebbr));
        WriteSceneryPacks("SCENERY_PACK Custom Scenery/Brussels HD/", "SCENERY_PACK *GLOBAL_AIRPORTS*");
        AirportFlattening flattening = Flattening();
        flattening.Flatten(Find(flattening.Load(CancellationToken.None), "EBBR"));
        WriteSceneryPacks("SCENERY_PACK Custom Scenery/Brussels HD/", $"SCENERY_PACK {FlattenedAirports.EntryPath}", "SCENERY_PACK *GLOBAL_AIRPORTS*");

        FlattenableAirport below = Find(flattening.Load(CancellationToken.None), "EBBR");
        Assert.False(below.InEffect);

        Assert.True(flattening.Flatten(below).InEffect);
        Assert.StartsWith($"I\r\n1000 Version\r\nSCENERY\r\n\r\nSCENERY_PACK {FlattenedAirports.EntryPath}\r\n", ScenerypacksText, StringComparison.Ordinal);
    }

    [Fact]
    public void A_new_package_goes_first_when_the_airports_package_is_not_listed()
    {
        WriteGlobalAirports(Ebbr);
        WriteSceneryPacks("SCENERY_PACK Custom Scenery/KSEA Demo/");
        AirportFlattening flattening = Flattening();

        FlattenableAirport flattened = flattening.Flatten(Find(flattening.Load(CancellationToken.None), "EBBR"));

        Assert.True(flattened.InEffect);
        Assert.StartsWith($"I\r\n1000 Version\r\nSCENERY\r\n\r\nSCENERY_PACK {FlattenedAirports.EntryPath}\r\n", ScenerypacksText, StringComparison.Ordinal);
    }

    [Fact]
    public void A_copy_whose_scenery_changed_since_is_outdated()
    {
        WriteGlobalAirports(Ebbr);
        WriteSceneryPacks("SCENERY_PACK *GLOBAL_AIRPORTS*");
        AirportFlattening flattening = Flattening();
        flattening.Flatten(Find(flattening.Load(CancellationToken.None), "EBBR"));

        WriteGlobalAirports(Ebbr.Replace("1302 city Brussels", "1302 city Bruxelles", StringComparison.Ordinal));
        FlattenableAirport outdated = Find(flattening.Load(CancellationToken.None), "EBBR");

        Assert.Equal(FlattenState.Outdated, outdated.State);
        flattening.Flatten(outdated);
        Assert.Equal(FlattenState.Flattened, Find(flattening.Load(CancellationToken.None), "EBBR").State);
        Assert.Contains("Bruxelles", File.ReadAllText(PackageAptDat), StringComparison.Ordinal);
    }

    [Fact]
    public void Without_a_scenery_list_the_package_is_written_and_X_Plane_lists_it_itself()
    {
        WriteGlobalAirports(Ebbr);
        AirportFlattening flattening = Flattening();

        FlattenableAirport flattened = flattening.Flatten(Find(flattening.Load(CancellationToken.None), "EBBR"));

        Assert.True(flattened.InEffect);
        Assert.True(File.Exists(PackageAptDat));
        Assert.False(File.Exists(_tree.PathOf("X-Plane 12/Custom Scenery/scenery_packs.ini")));
    }

    [Fact]
    public void A_flattened_airport_whose_scenery_is_gone_can_still_be_undone()
    {
        _tree.WriteText("X-Plane 12/Custom Scenery/Demo/Earth nav data/apt.dat", AptDat(Lsez.Replace("1302 flatten 1", "1302 city Zermatt", StringComparison.Ordinal)));
        WriteSceneryPacks("SCENERY_PACK Custom Scenery/Demo/");
        AirportFlattening flattening = Flattening();
        flattening.Flatten(Find(flattening.Load(CancellationToken.None), "LSEZ"));
        WriteSceneryPacks($"SCENERY_PACK {FlattenedAirports.EntryPath}");

        FlattenableAirport orphan = Find(flattening.Load(CancellationToken.None), "LSEZ");

        Assert.Null(orphan.Source);
        Assert.Equal(FlattenState.Flattened, orphan.State);
        Assert.Throws<InvalidOperationException>(() => flattening.Flatten(orphan));
        flattening.Undo(orphan);
        Assert.Empty(flattening.Load(CancellationToken.None));
    }
}
